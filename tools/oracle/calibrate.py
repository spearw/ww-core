"""Choose band cut-offs for the new rules that best reproduce WW's bands (Phase 1 spec §3.3).

Run: python3 tools/oracle/calibrate.py  → writes tools/oracle/calibration-report.md and
prints {"bands": {...}, "agree": n, "n": m}. William reviews the report before the cut-offs
go into the engine (Task 15).
"""

from __future__ import annotations

import datetime as dt
import json
import math
import statistics
from pathlib import Path

import ww_score
import ww_types
from app_io import app_to_ww, expand_suite, parse_case
from score import DEFAULT_WEIGHTS, Config, score_all

HERE = Path(__file__).resolve().parent
AS_OF = dt.date(2026, 9, 11)
WW_CUTS = {"NOW": 85.0, "NEXT": 60.0, "SOON": 35.0}
NAMES = ("NOW", "NEXT", "SOON")
LABEL = {"NOW": "Now", "NEXT": "Next", "SOON": "Soon", "SOMEDAY": "Later"}
LEANINGS = {
    "Default (0.40 / 0.30 / 0.20 / 0.10)": DEFAULT_WEIGHTS,
    "Builder (Unlocks more 0.44)": {"risk": 0.225, "value": 0.225, "finance": 0.11,
                                    "enablement": 0.44},
    "Investor (Money back 0.44)": {"risk": 0.225, "value": 0.225, "finance": 0.44,
                                   "enablement": 0.11},
}


def band_for(tenths: int, cuts: dict[str, int]) -> str:
    for name in NAMES:
        if tenths >= cuts[name]:
            return name
    return "SOMEDAY"


def place(lo: int, hi: float, ref: float) -> int | None:
    """A cut-off in tenths with lo < t <= hi, as close to ref as possible; a multiple of
    5 (i.e. 0.5) if the gap has one, else a whole tenth."""
    for step in (5, 1):
        k_lo = lo // step + 1
        k_hi = math.inf if hi == math.inf else int(hi) // step
        if k_lo <= k_hi:
            k = min(max(round(ref / step), k_lo), k_hi)
            return int(k * step)
    return None


def search(target: dict[str, str], tenths: dict[str, int], refs: dict[str, float]) -> dict:
    """Exhaustive over the gaps between scores: a cut-off only changes the result when it
    crosses a project's score. Most agreement wins; ties go to the triple closest to refs."""
    ids = sorted(target)
    values = sorted({tenths[i] for i in ids})
    index = {v: k for k, v in enumerate(values)}
    m = len(values)

    def lo(g: int) -> int:
        return values[g - 1] if g > 0 else 0

    def hi(g: int) -> float:
        return values[g] if g < m else math.inf

    best = None
    for g_now in range(m + 1):
        for g_next in range(g_now + 1):
            for g_soon in range(g_next + 1):
                gaps = {"NOW": g_now, "NEXT": g_next, "SOON": g_soon}
                agree = 0
                for i in ids:
                    k = index[tenths[i]]
                    band = next((n for n in NAMES if k >= gaps[n]), "SOMEDAY")
                    agree += band == target[i]
                cuts = {n: place(lo(gaps[n]), hi(gaps[n]), refs[n]) for n in NAMES}
                if None in cuts.values() or not cuts["NOW"] > cuts["NEXT"] > cuts["SOON"]:
                    continue
                dist = sum(abs(math.log(cuts[n] / refs[n])) for n in NAMES)
                key = (-agree, dist)
                if best is None or key < best[0]:
                    best = (key, {"cuts": cuts, "agree": agree, "n": len(ids)})
    if best is None:
        raise SystemExit("calibration: no valid cut-off triple")
    return best[1]


def ww_scores(cases: list[dict], weights: dict) -> dict:
    cfg = ww_types.EngineConfig(weights=dict(weights))
    return {r.id: r for r in ww_score.score_all([app_to_ww(c) for c in cases], cfg, AS_OF)}


def new_scores(cases: list[dict], weights: dict, members: list[str]) -> dict:
    cfg = Config(members=members, weights=dict(weights))
    return {r.id: r for r in score_all([parse_case(c) for c in cases], cfg, AS_OF)}


def forced(r) -> bool:
    return bool(r.forced_now or r.non_negotiable)


def spread(bands: list[str]) -> str:
    return " / ".join(str(bands.count(n)) for n in ("NOW", "NEXT", "SOON", "SOMEDAY"))


def render(cases, members, ww, new, ids, scale, refs, result, cuts) -> str:
    tenth_cuts = result["cuts"]
    lines = [
        "# Band cut-off calibration",
        "",
        f"Generated by `tools/oracle/calibrate.py` from the {len(ids)} calibration projects "
        f"in `tools/oracle/cases.json`, as of {AS_OF}. Scores under the new rules are "
        f"{scale:.2f}× WW's on the median project.",
        "",
        "## Cut-offs",
        "",
        "| Band | WW | WW × median increase | Chosen |",
        "|---|---|---|---|",
    ]
    for n in NAMES:
        lines.append(f"| {LABEL[n]} | {WW_CUTS[n]:g} | {refs[n] / 10:.1f} | **{cuts[n]:g}** |")
    lines += [
        "",
        f"Same band as WW's rules for **{result['agree']} of {result['n']}** projects "
        "(default priorities).",
        "",
        "## Projects that change band",
        "",
        "| Project | WW rules | New rules |",
        "|---|---|---|",
    ]
    changed = [i for i in ids if band_for(round(new[i].priority * 10), tenth_cuts) != ww[i].band]
    for i in sorted(changed, key=lambda i: -new[i].priority):
        nb = band_for(round(new[i].priority * 10), tenth_cuts)
        lines.append(f"| {new[i].title} | {LABEL[ww[i].band]} ({ww[i].priority:g}) "
                     f"| {LABEL[nb]} ({new[i].priority:g}) |")
    if not changed:
        lines.append("| (none) | | |")
    lines += [
        "",
        "## Band spread by leaning (Now / Next / Soon / Later)",
        "",
        "| Leaning | WW rules and cut-offs | New rules and cut-offs |",
        "|---|---|---|",
    ]
    for name, w in LEANINGS.items():
        wwb = [r.band for r in ww_scores(cases, w).values()]
        newb = ["NOW" if forced(r) else band_for(round(r.priority * 10), tenth_cuts)
                for r in new_scores(cases, w, members).values()]
        lines.append(f"| {name} | {spread(wwb)} | {spread(newb)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    suite = next(s for s in json.loads((HERE / "cases.json").read_text())["suites"]
                 if s["name"] == "calibration")
    cases, members = expand_suite(suite), suite["members"]
    ww = ww_scores(cases, DEFAULT_WEIGHTS)
    new = new_scores(cases, DEFAULT_WEIGHTS, members)
    ids = [i for i, r in new.items() if not forced(r)]
    target = {i: ww[i].band for i in ids}
    tenths = {i: round(new[i].priority * 10) for i in ids}
    scale = statistics.median(new[i].priority / ww[i].priority for i in ids if ww[i].priority > 0)
    refs = {n: WW_CUTS[n] * scale * 10 for n in NAMES}
    result = search(target, tenths, refs)
    cuts = {n: result["cuts"][n] / 10 for n in NAMES}
    (HERE / "calibration-report.md").write_text(
        render(cases, members, ww, new, ids, scale, refs, result, cuts))
    print(json.dumps({"bands": cuts, "agree": result["agree"], "n": result["n"]}))


if __name__ == "__main__":
    main()
