"""Regenerate src/engine/__fixtures__/conformance-app.json from the oracle.

Never edit that file by hand. CI re-runs this script and fails if the output differs.
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

from app_io import expand_suite, expect_of, parse_case, ww_cases_to_app
from score import DEFAULT_BANDS, DEFAULT_WEIGHTS, Config, score_all

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
WW = ROOT / "reference" / "ww-engine" / "conformance.json"
OUT = ROOT / "src" / "engine" / "__fixtures__" / "conformance-app.json"
AS_OF = "2026-09-11"
HORIZON_YEARS = 10


def suites() -> list[dict]:
    ww = json.loads(WW.read_text())
    inputs = ww_cases_to_app([c["input"] for c in ww["cases"]])
    ww_suite = {
        "name": "ww",
        "members": ["william", "partner"],
        "cases": [{"id": c["id"], "what": c["what"], "input": i}
                  for c, i in zip(ww["cases"], inputs, strict=True)],
    }
    own = []
    for s in json.loads((HERE / "cases.json").read_text())["suites"]:
        own.append({
            "name": s["name"],
            "members": s["members"],
            "cases": [{"id": c["id"], "what": c["what"], "input": i}
                      for c, i in zip(s["cases"], expand_suite(s), strict=True)],
        })
    return [ww_suite, *own]


def build() -> dict:
    as_of = dt.date.fromisoformat(AS_OF)
    out = []
    for s in suites():
        cfg = Config(members=s["members"])
        scored = {r.id: r for r in score_all([parse_case(c["input"]) for c in s["cases"]],
                                             cfg, as_of)}
        cases = [{**c, "expect": expect_of(scored[c["id"]]) if c["id"] in scored
                  else {"scored": False}} for c in s["cases"]]
        out.append({"name": s["name"], "members": s["members"], "cases": cases})
    return {
        "note": "Generated by tools/oracle/generate.py. Do not edit by hand.",
        "as_of": AS_OF,
        "weights": DEFAULT_WEIGHTS,
        "horizon_years": HORIZON_YEARS,
        "bands": DEFAULT_BANDS,
        "suites": out,
    }


def main() -> None:
    OUT.write_text(json.dumps(build(), indent=1, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
